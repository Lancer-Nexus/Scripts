#!/usr/bin/env python3
"""Classify catalog goods with no static market entry for explicit policy review."""

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path


def build_review(report_bytes):
    report = json.loads(report_bytes)
    if report.get("schemaVersion") != 1:
        raise ValueError("Unsupported market catalog report schema")

    goods = report.get("goods")
    unlisted = report.get("unlistedGoodIds")
    if not isinstance(goods, list) or not isinstance(unlisted, list):
        raise ValueError("Market catalog report is missing goods or unlistedGoodIds")

    by_id = {}
    for good in goods:
        good_id = good.get("goodId") if isinstance(good, dict) else None
        if not isinstance(good_id, str) or not good_id or good_id in by_id:
            raise ValueError("Market catalog contains an invalid or duplicate goodId")
        by_id[good_id] = good

    if any(not isinstance(good_id, str) for good_id in unlisted) or len(set(unlisted)) != len(unlisted):
        raise ValueError("unlistedGoodIds contains invalid or duplicate IDs")
    if not set(unlisted).issubset(by_id):
        raise ValueError("unlistedGoodIds references an unknown good")

    package_references = {}
    for package in goods:
        if package.get("category") != "ship":
            continue
        package_id = package["goodId"]
        hull_id = package.get("hullGoodId")
        if hull_id:
            package_references.setdefault(hull_id, []).append({"packageId": package_id, "role": "hull"})
        for addon in package.get("addons", []):
            equipment_id = addon.get("equipmentId") if isinstance(addon, dict) else None
            if equipment_id:
                package_references.setdefault(equipment_id, []).append({
                    "packageId": package_id,
                    "role": "addon",
                    "amount": addon.get("amount"),
                    "hardpoint": addon.get("hardpoint"),
                })

    rows = []
    for good_id in sorted(unlisted):
        good = by_id[good_id]
        category = good.get("category", "")
        source = good.get("source", "")
        references = sorted(package_references.get(good_id, []), key=lambda item: (item["packageId"], item["role"]))
        if category == "shiphull":
            review_class = "ship_hull_component" if references else "unreferenced_ship_hull"
        elif category == "commodity":
            review_class = "unlisted_commodity"
        elif category == "equipment" and references:
            review_class = "ship_package_addon"
        elif category == "equipment" and source == "weapon_good.ini":
            review_class = "unlisted_weapon"
        elif category == "equipment" and source == "st_good.ini":
            review_class = "special_equipment"
        elif category == "equipment" and source == "goods.ini":
            review_class = "other_equipment"
        else:
            review_class = "manual_classification_required"

        standalone_allowed = review_class not in ("ship_hull_component", "ship_package_addon")
        rows.append({
            "goodId": good_id,
            "category": category,
            "definitionSource": source,
            "legacyPrice": good.get("price"),
            "packageReferences": references,
            "reviewClass": review_class,
            "standaloneTradePolicy": "not_reviewed" if standalone_allowed else "package_component_only",
            "marketPolicyStatus": "disabled_until_explicit_review",
        })

    return {
        "schemaVersion": 1,
        "catalogReportSha256": hashlib.sha256(report_bytes).hexdigest(),
        "catalogReportSchemaVersion": report["schemaVersion"],
        "unlistedGoodCount": len(rows),
        "reviewClassCounts": dict(sorted(Counter(row["reviewClass"] for row in rows).items())),
        "activationRule": "Every listed market/good pair stays disabled until an explicit reviewed stock policy enables it.",
        "goods": rows,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path, help="market catalog JSON generated by analyze-market-catalog.py")
    parser.add_argument("--output", type=Path, required=True, help="review JSON output path")
    args = parser.parse_args()
    review = build_review(args.report.read_bytes())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(review, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {review['unlistedGoodCount']} unlisted-good review rows; market policy remains disabled.")


if __name__ == "__main__":
    main()
