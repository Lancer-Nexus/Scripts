#!/usr/bin/env python3
"""Create a report-pinned review of market and base faction mappings."""

import argparse
import hashlib
import json
from pathlib import Path


def build_review(report_bytes):
    report = json.loads(report_bytes)
    if report.get("schemaVersion") != 1 or not isinstance(report.get("markets"), list):
        raise ValueError("Unsupported or malformed market catalog report")

    markets = []
    seen = set()
    for row in report["markets"]:
        if not isinstance(row, dict):
            raise ValueError("Market catalog contains a malformed market")
        market_id = row.get("marketId")
        local_faction = row.get("localFactionId")
        base_factions = row.get("baseFactionIds")
        system_ids = row.get("systemIds")
        entry_count = row.get("entryCount")
        buyable_good_count = row.get("buyableGoodCount")
        if not isinstance(market_id, str) or not market_id.strip() or market_id in seen:
            raise ValueError("Market catalog contains an invalid or duplicate marketId")
        if not isinstance(local_faction, str) or not local_faction.strip():
            raise ValueError(f"Market {market_id} has no localFactionId")
        if (not isinstance(base_factions, list) or
                any(not isinstance(value, str) or not value.strip() for value in base_factions) or
                len(set(base_factions)) != len(base_factions)):
            raise ValueError(f"Market {market_id} has invalid baseFactionIds")
        if (not isinstance(system_ids, list) or
                any(not isinstance(value, str) or not value.strip() for value in system_ids)):
            raise ValueError(f"Market {market_id} has invalid systemIds")
        if isinstance(entry_count, bool) or not isinstance(entry_count, int) or entry_count < 0:
            raise ValueError(f"Market {market_id} has an invalid entryCount")
        if (isinstance(buyable_good_count, bool) or not isinstance(buyable_good_count, int) or
                buyable_good_count < 0 or buyable_good_count > entry_count):
            raise ValueError(f"Market {market_id} has an invalid buyableGoodCount")

        seen.add(market_id)
        if local_faction not in base_factions:
            markets.append({
                "marketId": market_id,
                "systemIds": sorted(set(system_ids)),
                "localFactionId": local_faction,
                "baseFactionIds": sorted(base_factions),
                "entryCount": entry_count,
                "buyableGoodCount": buyable_good_count,
                "hasStaticMarketEntries": entry_count > 0,
                "hasBuyableGoods": buyable_good_count > 0,
            })

    markets.sort(key=lambda row: row["marketId"])
    market_count = len(report["markets"])
    static_entry_market_count = sum(row["entryCount"] > 0 for row in report["markets"])
    buyable_market_count = sum(row["buyableGoodCount"] > 0 for row in report["markets"])
    static_entry_mismatches = sum(row["hasStaticMarketEntries"] for row in markets)
    buyable_mismatches = sum(row["hasBuyableGoods"] for row in markets)
    return {
        "schemaVersion": 1,
        "catalogReportSha256": hashlib.sha256(report_bytes).hexdigest(),
        "summary": {
            "marketCount": market_count,
            "marketsWithStaticMarketEntries": static_entry_market_count,
            "marketsWithBuyableGoods": buyable_market_count,
            "localFactionMissingCount": 0,
            "localFactionOutsideBaseFactionCount": len(markets),
            "mismatchedMarketsWithStaticMarketEntriesCount": static_entry_mismatches,
            "mismatchedMarketsWithBuyableGoodsCount": buyable_mismatches,
        },
        "interpretation": {
            "marketFactionSource": "MBase.local_faction",
            "baseFactionRole": "NPC- und Missionskontext; kein Fallback für die Marktruf-Fraktion",
            "mismatchAuthorizesOffers": False,
        },
        "marketsWithLocalFactionOutsideBaseFaction": markets,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path, help="market catalog JSON generated by analyze-market-catalog.py")
    parser.add_argument("--output", type=Path, required=True, help="review JSON output path")
    args = parser.parse_args()
    review = build_review(args.report.read_bytes())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(review, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    summary = review["summary"]
    print(f"Wrote {summary['localFactionOutsideBaseFactionCount']} faction mapping reviews; "
          f"{summary['mismatchedMarketsWithStaticMarketEntriesCount']} have static market entries, "
          f"{summary['mismatchedMarketsWithBuyableGoodsCount']} have buyable goods.")


if __name__ == "__main__":
    main()
